// 📱 1. Smartphone
// Attributes (Properties)
    // model
    // color
    // price

// Behaviors (Methods)
    // makeCall()
    // playMusic()
    // takePhoto()

// OOP Concepts

    // Abstraction:
    // The user can easily take a photo by pressing a button — the complex internal camera operations (lens focus, lighting, image processing) are hidden from the user.

    // Encapsulation:
    // Internal data like volume level or battery percentage is protected; users can access them only through specific settings or interfaces.

    // Polymorphism:
    // The playMusic() function may behave differently across devices (e.g., Android, iPhone) but the method name remains the same.

    // Inheritance:
    // The Smartphone can inherit basic functions from a generic MobilePhone class (like makeCall() and sendSMS()), then extend them with new features (like browseInternet() or takePhoto()).

    // Composition:
    // A Smartphone “has a” Camera and a MusicPlayer inside it — those are separate components combined to create the overall functionality.

// 🚲 2. Bicycle
    // Attributes (Properties)
        // color
        // gearCount
        // speed

    // Behaviors (Methods)
        // pedal()
        // brake()
        // changeGear()

    // OOP Concepts

    // Abstraction:
    // When a rider uses brakes, they don’t need to know whether it’s a disc or rim brake — the braking process is simplified for the user.

    // Encapsulation:
    // The gear system and chain mechanisms are enclosed and protected; the rider interacts through levers and pedals, not directly with the inner parts.

    // Polymorphism:
    // The brake() method works differently in different bicycle types (e.g., mountain bike vs. road bike), though the action name is the same.

    // Inheritance:
    // Specialized bicycles like MountainBike or ElectricBike can inherit common properties and methods from the base Bicycle class and add new features like useBattery() or suspensionControl().

    // Composition:
    // A Bicycle “has” components like wheels, gears, and brakes — each part has its own function, but they work together to make the bicycle operate.

// 🏫 3. School
    // Attributes (Properties)
        // name
        // location
        // noOfStudents

    // Behaviors (Methods)
        // conductClass()
        // admitStudent()
        // organizeEvent()

    // OOP Concepts

    // Abstraction:
    // The conductClass() process hides complex internal scheduling, teacher assignments, and subject management — the user just sees a timetable.

    // Encapsulation:
    // Student data, grades, and personal information are kept secure within the school system — only authorized staff can access them.

    // Polymorphism:
    // The conductClass() method behaves differently in different types of schools — a primary school, high school, or college conducts classes in its own way.

    // Inheritance:
    // A HighSchool or College class can inherit from a general School class and add specialized methods like conductExam() or grantDegree().

    // Composition:
    // A School “has” Teachers, Students, and Classrooms — these individual objects together form the complete school system.


